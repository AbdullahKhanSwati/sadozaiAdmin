-- 1) Categories that don't exist yet
insert into public.expense_categories (name, sort_order)
select c.category,
       (select coalesce(max(sort_order), 0) from public.expense_categories) + row_number() over (order by c.category)
  from (select distinct category from hist_exp) c
 where not exists (select 1 from public.expense_categories ec where lower(ec.name) = lower(c.category));

-- Use the category's existing spelling where it differs only in capitals.
update hist_exp h
   set category = ec.name
  from public.expense_categories ec
 where lower(ec.name) = lower(h.category) and ec.name <> h.category;

-- 2) Which rows are new. For each identical expense (same date, description,
--    amount, category) only the copies the database doesn't have yet are added.
drop table if exists hist_new;
create temp table hist_new as
select h.*
  from (
    select h.*,
           row_number() over (partition by h.spent_on, lower(h.description), h.amount, lower(h.category) order by h.n) as copy_no
      from hist_exp h
  ) h
 where h.copy_no > (
   select count(*) from public.expenses e
    where e.spent_on = h.spent_on
      and lower(coalesce(e.description, '')) = lower(h.description)
      and e.amount = h.amount
      and lower(coalesce(e.category, '')) = lower(h.category)
 );

-- 3) Add them
insert into public.expenses (category, amount, description, spent_on, created_at)
select category, amount, description, spent_on,
       (spent_on + spent_time) at time zone 'Asia/Karachi'
  from hist_new
 order by n;

-- 4) Result
select (select count(*) from hist_exp)                       as rows_in_file,
       (select count(*) from hist_new)                       as added_now,
       (select count(*) from hist_exp) - (select count(*) from hist_new) as skipped_already_there,
       (select coalesce(sum(amount), 0) from hist_new)        as amount_added,
       (select count(*) from public.expenses)                 as expenses_in_database_now;

